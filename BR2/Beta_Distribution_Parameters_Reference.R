cat("\n╔═══════════════════════════════════════════════════════════════════╗\n")
cat("║           Alpha和Beta参数的变化规律总结                        ║\n")
cat("╚═══════════════════════════════════════════════════════════════════╝\n\n")

cat("【关于Alpha (α)】\n")
cat("  当α增大时:\n")
cat("  • 分布向右移动\n")
cat("  • 平均值增大 (因为E[θ] = α/(α+β))\n")
cat("  • 分布变得更尖锐(信息增加)\n\n")

cat("【关于Beta (β)】\n")
cat("  当β增大时:\n")
cat("  • 分布向左移动\n")
cat("  • 平均值减小 (因为E[θ] = α/(α+β))\n")
cat("  • 分布变得更尖锐(信息增加)\n\n")

cat("【关于Alpha和Beta的组合】\n")
cat("  α > β:\n")
cat("    • 分布右倾(向高值倾斜)\n")
cat("    • 平均值 > 0.5\n")
cat("    • 众数 > 0.5\n")
cat("    • 应用：相信高成功率\n\n")

cat("  α < β:\n")
cat("    • 分布左倾(向低值倾斜)\n")
cat("    • 平均值 < 0.5\n")
cat("    • 众数 < 0.5\n")
cat("    • 应用：相信低成功率\n\n")

cat("  α = β:\n")
cat("    • 分布对称\n")
cat("    • 平均值 = 0.5\n")
cat("    • 众数 = 0.5(当α=β>1时)\n")
cat("    • 应用：确信在中间值\n\n")

cat("  α+β很大:\n")
cat("    • 分布非常集中(尖锐)\n")
cat("    • 信息量大\n")
cat("    • 数据或先验都很充分\n\n")

cat("  α+β很小:\n")
cat("    • 分布很分散(平缓)\n")
cat("    • 信息量小\n")
cat("    • 表示不确定性大\n\n")

