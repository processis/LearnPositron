# 第四部分：贝叶斯更新过程说明
# ============================================================

cat("\n╔═══════════════════════════════════════════════════════════════════╗\n")
cat("║         贝叶斯更新过程：从先验到后验                           ║\n")
cat("╚═══════════════════════════════════════════════════════════════════╝\n\n")

cat("【贝叶斯更新的数学过程】\n\n")
cat("一般形式：\n")
cat("  α_后验 = α_先验 + 成功次数(x)\n")
cat("  β_后验 = β_先验 + 失败次数(n-x)\n\n")

cat("【具体例子：重复1】\n")
cat("  原始数据：N=25, x=19 (19次成功，6次失败)\n\n")

cat("  Prior 0.5 分析：\n")
cat("  ├─ 先验：Beta(1, 1)\n")
cat("  │   • 代表：1次"虚拟"成功，1次"虚拟"失败\n")
cat("  │   • 含义：完全无知\n")
cat("  ├─ 数据：19次成功，6次失败\n")
cat("  ├─ 后验：Beta(1+19, 1+6) = Beta(20, 7)\n")
cat("  │   • α_后验 = 1 + 19 = 20\n")
cat("  │   • β_后验 = 1 + 6 = 7\n")
cat("  └─ 结果：\n")
cat("      • 平均值 = 20/27 ≈ 0.741\n")
cat("      • 众数 ≈ 0.760\n")
cat("      • 信息强度 = 27\n\n")

cat("  Prior 0.75 分析：\n")
cat("  ├─ 先验：Beta(6, 2)\n")
cat("  │   • 代表：6次"虚拟"成功，2次"虚拟"失败\n")
cat("  │   • 含义：相信75%的成功率\n")
cat("  ├─ 数据：19次成功，6次失败\n")
cat("  ├─ 后验：Beta(6+19, 2+6) = Beta(25, 8)\n")
cat("  │   • α_后验 = 6 + 19 = 25\n")
cat("  │   • β_后验 = 2 + 6 = 8\n")
cat("  └─ 结果：\n")
cat("      • 平均值 = 25/33 ≈ 0.758\n")
cat("      • 众数 ≈ 0.774\n")
cat("      • 信息强度 = 33\n\n")

cat("【为什么Prior 0.75的结果更高？】\n")
cat("  1. 先验已经倾向0.75（高于0.5）\n")
cat("  2. 数据本身也显示高成功率（19/25=0.76）\n")
cat("  3. 两种信息同向，后验进一步向右倾移\n")
cat("  4. 信息强度也更大（33 > 27）\n\n")

