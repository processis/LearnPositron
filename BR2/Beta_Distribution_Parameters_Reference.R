cat("【8个实验的Beta分布参数详解】\n\n")

# 原始数据
experiments_data <- data.frame(
  exp_name = c("实验1", "重复1", "重复2", "重复3", "重复4", "重复5", "重复6", "重复7"),
  N = c(28, 25, 12, 12, 11, 10, 10, 5),
  x = c(17, 19, 8, 9, 8, 7, 8, 4)
)

# 计算所有参数
results_detail <- experiments_data %>%
  mutate(
    # Prior 0.5的参数
    prior_05_a = 1,
    prior_05_b = 1,
    
    # Prior 0.75的参数
    prior_75_a = 6,
    prior_75_b = 2,
    
    # 后验参数（贝叶斯更新）
    post_05_a = prior_05_a + x,
    post_05_b = prior_05_b + (N - x),
    post_75_a = prior_75_a + x,
    post_75_b = prior_75_b + (N - x),
    
    # 后验统计量
    mean_05 = post_05_a / (post_05_a + post_05_b),
    mean_75 = post_75_a / (post_75_a + post_75_b),
    
    mode_05 = ifelse(post_05_a > 1 & post_05_b > 1, 
                     (post_05_a - 1) / (post_05_a + post_05_b - 2), 
                     NA),
    mode_75 = ifelse(post_75_a > 1 & post_75_b > 1, 
                     (post_75_a - 1) / (post_75_a + post_75_b - 2), 
                     NA),
    
    # 信息强度
    info_05 = post_05_a + post_05_b,
    info_75 = post_75_a + post_75_b,
    
    # 参数比值（决定分布方向）
    ratio_05 = post_05_a / post_05_b,
    ratio_75 = post_75_a / post_75_b
  )

# 详细输出每个实验
for(i in 1:nrow(results_detail)) {
  row <- results_detail[i,]
  
  cat(sprintf("【%s】N=%d, x=%d, 成功率=%.2f%%\n", 
              row$exp_name, row$N, row$x, (row$x/row$N)*100))
  
  cat(sprintf("├─ Prior 0.5 (无信息先验) Beta(1, 1)\n"))
  cat(sprintf("│  ├─ 后验参数: Beta(%.0f, %.0f)\n", row$post_05_a, row$post_05_b))
  cat(sprintf("│  ├─ 平均值: %.4f\n", row$mean_05))
  cat(sprintf("│  ├─ 众数: %.4f\n", row$mode_05))
  cat(sprintf("│  ├─ α/β比值: %.4f", row$ratio_05))
  if(row$ratio_05 > 1) cat(" → 右倾")
  if(row$ratio_05 < 1) cat(" → 左倾")
  if(abs(row$ratio_05 - 1) < 0.01) cat(" → 对称")
  cat("\n")
  cat(sprintf("│  └─ 信息强度(α+β): %.0f\n", row$info_05))
  
  cat(sprintf("│\n"))
  cat(sprintf("├─ Prior 0.75 (有信息先验) Beta(6, 2)\n"))
  cat(sprintf("│  ├─ 后验参数: Beta(%.0f, %.0f)\n", row$post_75_a, row$post_75_b))
  cat(sprintf("│  ├─ 平均值: %.4f\n", row$mean_75))
  cat(sprintf("│  ├─ 众数: %.4f\n", row$mode_75))
  cat(sprintf("│  ├─ α/β比值: %.4f", row$ratio_75))
  if(row$ratio_75 > 1) cat(" → 右倾")
  if(row$ratio_75 < 1) cat(" → 左倾")
  if(abs(row$ratio_75 - 1) < 0.01) cat(" → 对称")
  cat("\n")
  cat(sprintf("│  └─ 信息强度(α+β): %.0f\n", row$info_75))
  
  cat(sprintf("│\n"))
  cat(sprintf("└─ 两个先验的对比\n"))
  cat(sprintf("   • 平均值差异: %.4f (Prior 0.75更高)\n", row$mean_75 - row$mean_05))
  cat(sprintf("   • 信息强度差异: %.0f (Prior 0.75更强)\n", row$info_75 - row$info_05))
  cat(sprintf("   • 分布集中度: Prior 0.75更尖锐\n\n"))
}

